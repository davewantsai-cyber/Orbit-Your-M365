import shutil
from pathlib import Path

import pytest
from docx import Document

from orbit.config import FOOTER
from orbit.reporting import parser
from orbit.reporting.context import ReportContext
from orbit.reporting.docx_report import generate_docx
from orbit.reporting.pdf_report import generate_pdf

FIX = Path(__file__).parent / "fixtures"


@pytest.fixture()
def ctx():
    f = parser.parse_files({"scubagear": FIX / "scubagear_sample.json",
                            "maester": FIX / "maester_sample.json"})
    return ReportContext(f, ["ScubaGear", "Maester"], dry_run=True)


def test_docx_contents(ctx, tmp_path):
    p = generate_docx(ctx, tmp_path)
    assert p.name == "ORBIT_Summary_DRYRUN.docx"
    d = Document(str(p))
    text = "\n".join(x.text for x in d.paragraphs)
    assert "ORBIT Assessment Summary (DRY RUN)" in text
    assert "Reece Gabriel Dickson" in text and "[Client Name]" in text
    assert "50.0%" in text and "CVE-2022-21972" in text
    assert d.sections[0].footer.paragraphs[0].text == FOOTER
    assert len(d.tables[1].rows) == 1 + 16  # header + all findings
    sev = {r.cells[0].text: r.cells[1].text for r in d.tables[0].rows[1:]}
    assert sev["Critical"] == "1" and sev["Pass"] == "8"


def test_pdf_core_font_text(ctx, tmp_path):
    p = generate_pdf(ctx, tmp_path, use_unicode=False)
    data = p.read_bytes()
    assert data.startswith(b"%PDF") and p.name == "ORBIT_Summary_DRYRUN.pdf"
    for needle in (b"ORBIT Assessment Summary", b"DRY RUN", b"Reece Gabriel Dickson",
                   b"CVE-2022-21972", b"50.0%", b"Generated by ORBIT v1.2.0"):
        assert needle in data, needle


def test_pdf_unicode_path_generates(ctx, tmp_path):
    p = generate_pdf(ctx, tmp_path, use_unicode=True)
    assert p.stat().st_size > 1000


def test_real_run_filenames(tmp_path):
    c = ReportContext([], [], dry_run=False)
    assert generate_docx(c, tmp_path).name == "ORBIT_Summary.docx"
    assert generate_pdf(c, tmp_path, use_unicode=False).name == "ORBIT_Summary.pdf"


def test_client_name_on_cover(ctx, tmp_path):
    ctx.client = "Acme Ltd"
    d = Document(str(generate_docx(ctx, tmp_path)))
    assert "Acme Ltd" in "\n".join(x.text for x in d.paragraphs)
    assert b"Acme Ltd" in generate_pdf(ctx, tmp_path, use_unicode=False).read_bytes()


def test_blank_client_defaults_to_confidential(tmp_path):
    from orbit.core.outputs import OutputConfig
    from orbit.core.pipeline import finalize
    shutil.copy(FIX / "scubagear_sample.json", tmp_path / "scubagear_sample.json")
    cfg = OutputConfig(base_dir=tmp_path, formats={"PDF", "DOCX"})
    _, written = finalize(tmp_path, ["ScubaGear"], cfg, True, client="  ")
    docx = next(p for p in written if p.suffix == ".docx")
    assert "Client: Confidential" in "\n".join(x.text for x in Document(str(docx)).paragraphs)
